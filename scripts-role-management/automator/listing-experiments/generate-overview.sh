#!/bin/bash
# generate-overview.sh
#
# Scans the personalbook for files starting with "Tinker*" (experiments),
# and generates a markdown checklist with clickable iA Writer links.
#
# Output:
#   - Overview.md (markdown checklist of all experiments)
#
# Usage: ./generate-overview.sh

DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" >/dev/null 2>&1 && pwd )"

# Example ia writer link:
#  ia-writer://open?path=/Locations/personalbook/roles/The%20Ideator/Brainstorming%20Projects/Brainstorming%20Experiments/generate-index.sh

function file_to_md_link() {
  local F=${1}
  local IA_WRITER_PATH=$(echo "ia-writer://open?path=${2}/${F}" | sed 's/ /%20/g')
  echo "- [ ] ["$(basename "${F}" | sed -e "s/.md//g" -e "s/.txt//g")"](${IA_WRITER_PATH})"
}
export -f file_to_md_link

function generate_overview() {
  echo "# Overview"
  echo "- Autogenerated  by ${DIR}/${0}"
  cd "${DIR}/../../../.." && find . -name 'Tinker*' -exec bash -c 'file_to_md_link "${0}" "${1}"' {} "/Locations/personalbook" \; | sort
}

generate_overview > "${DIR}/Overview.md"
